    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        String patientIdInput = JOptionPane.showInputDialog("Enter patient ID:");
        String firstName = "";
        String query1 = "SELECT `first_name` FROM `patientinfo` WHERE `id`=?";

        try {
            ps = connection.createConnection().prepareStatement(query1);
            ps.setString(1, patientIdInput);
            rs = ps.executeQuery();
            if (rs.next()) {
                firstName = rs.getString("first_name");
            }

        } catch (SQLException ex) {
            Logger.getLogger(MedicineData.class.getName()).log(Level.SEVERE, null, ex);
        }

        String query3 = "INSERT INTO `prescriptions` (patient_id, first_name, medicine_name, dosage, storage_cond, medicine_id) VALUES (?, ?, ?, ?, ?, ?)";
        try {
            ps = connection.createConnection().prepareStatement(query3);
            ps.setString(1, patientIdInput);
            ps.setString(2, firstName);
            ps.setString(3, jTextPaneMedName.getText());
            ps.setString(4, jTextPaneDosage.getText());
            ps.setString(5, jTextPaneStorage.getText());
            ps.setString(6, jTextPaneMedID.getText());
            ps.executeUpdate();
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(rootPane, "A Prescription for this Patient is already existed, please delete the first one ", "Add Error", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_jButton3ActionPerformed

